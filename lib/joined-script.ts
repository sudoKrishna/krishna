// Scripts whose glyphs join together when rendered (Arabic, Indic, etc.).
const JOINED_SCRIPT =
  /[\u0600-\u06ff\u0750-\u077f\u08a0-\u08ff\ufb50-\ufdff\ufe70-\ufeff\u0900-\u097f\u0980-\u09ff\u0a00-\u0a7f\u0a80-\u0aff\u0b00-\u0b7f\u0b80-\u0bff\u0c00-\u0c7f\u0c80-\u0cff\u0d00-\u0d7f]/;

export function joinsLetters(text: string) {
  return JOINED_SCRIPT.test(text);
}
